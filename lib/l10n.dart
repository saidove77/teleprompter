/// ترجمة نص: tr('key') أو tr('key', {'n': '5'})
String tr(String key, [Map<String, String>? args]) {
  var s = L10n._strings[L10n.code]?[key] ?? L10n._strings['en']?[key] ?? key;
  if (args != null) {
    args.forEach((k, v) => s = s.replaceAll('{$k}', v));
  }
  return s;
}

