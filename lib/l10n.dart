/// يعيد بناء محتواه عند تغيير لغة التطبيق
class LangBuilder extends StatelessWidget {
  const LangBuilder({super.key, required this.builder});

  final WidgetBuilder builder;

  @override
  Widget build(BuildContext context) {
    return ValueListenableBuilder<String>(
      valueListenable: L10n.lang,
      builder: (ctx, _, __) => builder(ctx),
    );
  }
}

/// تطبيق Material يتبع لغة التطبيق (الاتجاه RTL/LTR تلقائياً من اللغة)
Widget localizedApp({required Widget home}) {
  return ValueListenableBuilder<String>(
    valueListenable: L10n.lang,
    builder: (_, code, __) => MaterialApp(
      debugShowCheckedModeBanner: false,
      onGenerateTitle: (_) => tr('app_name'),
      theme: buildAppTheme(),
      locale: Locale(code),
      supportedLocales: [for (final l in kLangs) Locale(l.code)],
      localizationsDelegates: GlobalMaterialLocalizations.delegates,
      home: home,
    ),
  );
}
